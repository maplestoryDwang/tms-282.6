package net.swordie.ms.client.character.items;

import net.swordie.ms.connection.protocol.Protocol;
import net.swordie.ms.connection.protocol.ProtocolVersion;
import net.swordie.ms.constants.GameConstants;
import net.swordie.ms.enums.ItemGrade;
import net.swordie.ms.loaders.enhance.EnhanceTables;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Collections;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * TMS 282 enhancement item judgments from the 282 client's own item data (data/resources/tms282/enhance/
 * enhance-items.tsv, generated by _gen_enhance_items.py from data/wz282) instead of the GMS 265 id ranges:
 * rebirth flames (exGrade/createType/exNew/EOL, choice window from the 282 text), star force scrolls
 * (forceUpgrade, forceUpgradeWz2 incForce/maxUpgrade, noSuperior, reqEquipLevelMin/Max, 驚奇 rate table),
 * innocence scrolls (reset/perfectReset/arcReset) and bonus potential scrolls (grade from the 282 name).
 * <p>
 * Only consulted when the 282 profile is {@link #active()}; the 265 profile never loads the table. The plan
 * methods are pure (no Char, no packets) so tools/Tms282EnhanceItemsCheck can verify every 282 item offline.
 */
public final class Tms282EnhanceItems {

    public enum Family { FLAME, STAR, RESET, BONUS_POTENTIAL }

    public enum ResetKind { NONE, NORMAL, PERFECT, ARC }

    /** One row of enhance-items.tsv. */
    public record Entry(int itemId, Family family, Map<String, String> attrs, String name) {
        public int i(String key, int def) {
            String v = attrs.get(key);
            if (v == null || v.isBlank()) return def;
            try {
                return Integer.parseInt(v.trim());
            } catch (NumberFormatException e) {
                return def;
            }
        }

        public boolean flag(String key) {
            return i(key, 0) != 0;
        }

        public boolean has(String key) {
            return attrs.containsKey(key);
        }
    }

    private Tms282EnhanceItems() { }

    private static final class Holder {
        static final Map<Integer, Entry> ENTRIES = load();
    }

    public static boolean active() {
        return Protocol.active().version() == ProtocolVersion.TMS_282_3;
    }

    public static Path path() {
        return EnhanceTables.dir().resolve("enhance-items.tsv");
    }

    static Map<Integer, Entry> parse(List<String> lines) {
        Map<Integer, Entry> out = new HashMap<>();
        boolean header = true;
        for (String line : lines) {
            if (line.isBlank() || line.startsWith("#")) continue;
            if (header) { header = false; continue; }
            String[] c = line.split("\t", -1);
            if (c.length < 3) throw new IllegalArgumentException("Malformed enhance item: " + line);
            int id = Integer.parseInt(c[0].trim());
            Family family = Family.valueOf(c[1].trim());
            Map<String, String> attrs = new HashMap<>();
            for (String kv : c[2].split(";")) {
                if (kv.isBlank()) continue;
                int eq = kv.indexOf('=');
                if (eq <= 0) throw new IllegalArgumentException("Malformed attr " + kv + " in " + line);
                attrs.put(kv.substring(0, eq).trim(), kv.substring(eq + 1).trim());
            }
            if (out.put(id, new Entry(id, family, Map.copyOf(attrs), c.length > 3 ? c[3] : "")) != null) {
                throw new IllegalArgumentException("Duplicate enhance item " + id);
            }
        }
        return Map.copyOf(out);
    }

    private static Map<Integer, Entry> load() {
        Path p = path();
        if (!EnhanceTables.enabled() || !Files.isRegularFile(p)) {
            System.err.println("[enhance] " + p + " missing: 282 enhancement judgments fall back to the 265 id ranges");
            return Collections.emptyMap();
        }
        try {
            return parse(Files.readAllLines(p, StandardCharsets.UTF_8));
        } catch (IOException | RuntimeException e) {
            System.err.println("[enhance] cannot read " + p + ": " + e);
            return Collections.emptyMap();
        }
    }

    public static Map<Integer, Entry> all() {
        return Holder.ENTRIES;
    }

    public static Entry get(int itemId) {
        return Holder.ENTRIES.get(itemId);
    }

    public static Entry get(int itemId, Family family) {
        Entry e = get(itemId);
        return e != null && e.family() == family ? e : null;
    }

    public static boolean isFlame(int itemId) {
        return get(itemId, Family.FLAME) != null;
    }

    public static boolean isBonusPotentialScroll(int itemId) {
        return get(itemId, Family.BONUS_POTENTIAL) != null;
    }

    public static ResetKind resetKind(int itemId) {
        Entry e = get(itemId, Family.RESET);
        if (e == null) return ResetKind.NONE;
        if (e.flag("arcReset")) return ResetKind.ARC;
        if (!e.flag("reset")) return ResetKind.NONE;
        return e.flag("perfectReset") ? ResetKind.PERFECT : ResetKind.NORMAL;
    }

    // ---- flames ----------------------------------------------------------------------------------------------

    /** A flame decision: {@code refusal} (player text, the flame is not consumed) or the createType rule key. */
    public record FlamePlan(String refusal, int createType) {
        public boolean refused() {
            return refusal != null;
        }
    }

    /** createType used for a 282 exNew flame without one (週年武器專用): flame-rules.tsv row 0. */
    public static final int NO_CREATE_TYPE = 0;

    public static FlamePlan flame(Entry e, int equipLevel) {
        if (e == null || e.family() != Family.FLAME) return new FlamePlan("該物品不能用於此裝備。", -1);
        if (e.flag("nodata")) return new FlamePlan("此輪迴星火在目前版本沒有資料，道具未消耗。", -1);
        if (e.flag("eol") || !e.flag("exNew")) return new FlamePlan("此輪迴星火已停止使用（只能分解），道具未消耗。", -1);
        if (equipLevel > e.i("reqEquipLevelMax", 250)) return new FlamePlan("裝備等級不滿足物品要求。", -1);
        if (e.flag("choice")) return new FlamePlan("此輪迴星火（需選擇前後結果）目前尚未支援，道具未消耗。", -1);
        return new FlamePlan(null, e.i("createType", NO_CREATE_TYPE));
    }

    // ---- star force scrolls -------------------------------------------------------------------------------------

    /**
     * A star force scroll decision. {@code success}/{@code cursed} in percent; on success the equip gets
     * {@code targetStars}. {@code scrollProtection}: whether a 卷軸保護卡 (ScrollProtection) may keep the scroll.
     */
    public record StarPlan(String refusal, int success, int cursed, int targetStars, boolean scrollProtection) {
        public boolean refused() {
            return refusal != null;
        }

        static StarPlan refuse(String why) {
            return new StarPlan(why, 0, 0, 0, false);
        }
    }

    /** Equip facts a star scroll judgment needs (so the check can build them without an Equip). */
    public record StarTarget(int level, int stars, int maxStars, int tuc, boolean superior, boolean upgradable) {
        public static StarTarget of(Equip equip, boolean upgradable) {
            return new StarTarget(equip.getrLevel() + equip.getiIncReq(), equip.getChuc(), GameConstants.getMaxStars(equip),
                    equip.getTuc(), equip.isSuperiorEqp(), upgradable);
        }
    }

    public static StarPlan star(Entry e, StarTarget t) {
        if (e == null || e.family() != Family.STAR) return StarPlan.refuse("該物品不能用於此裝備。");
        if (e.flag("nodata")) return StarPlan.refuse("此卷軸在目前版本沒有資料，道具未消耗。");
        if (!t.upgradable()) return StarPlan.refuse("此裝備無法強化。");
        if (e.has("reqEquipLevelMin") && t.level() < e.i("reqEquipLevelMin", 0)
                || e.has("reqEquipLevelMax") && t.level() > e.i("reqEquipLevelMax", Integer.MAX_VALUE)) {
            return StarPlan.refuse("裝備等級不滿足物品要求。");
        }
        boolean ticket = e.flag("noSuperior");
        int success = e.i("success", 100);
        int force = e.i("forceUpgrade", 0);
        int inc = e.i("incForce", 0);
        if (force > 0) {
            if (ticket && t.superior()) return StarPlan.refuse("尊貴裝備無法使用此道具。");
            if (t.superior() && t.level() <= 94 && force > 3) return StarPlan.refuse("尊貴裝備無法使用此強化卷軸。");
            // 裝備強化卷軸 (no noSuperior) work on equipment whose upgrades are finished; the 星力強化券 do not say so.
            if (!ticket && t.tuc() != 0) return StarPlan.refuse("只能用於卷軸強化次數已用完的裝備。");
            if (t.stars() >= force) return StarPlan.refuse("裝備的星力已達到或超過 " + force + " 星。");
            if (t.maxStars() < force) return StarPlan.refuse("此裝備的最大星力低於 " + force + " 星。");
            return new StarPlan(null, success, e.i("cursed", 0), force, !ticket);
        }
        if (inc > 0) {
            int max = e.i("maxUpgrade", 0);
            if (t.superior()) return StarPlan.refuse("尊貴裝備無法使用此道具。");
            if (t.stars() >= max) return StarPlan.refuse("裝備的星力已達到或超過 " + max + " 星。");
            if (t.maxStars() < max) return StarPlan.refuse("此裝備的最大星力低於 " + max + " 星。");
            return new StarPlan(null, success, 0, Math.min(max, t.stars() + inc), false);
        }
        if (e.has("amazingRates")) {
            int maxStar = e.i("amazingMaxStar", 15);
            if (t.superior()) return StarPlan.refuse("尊貴裝備無法使用此卷軸。");
            if (t.stars() >= maxStar) return StarPlan.refuse("無法用於 " + maxStar + " 星以上的道具。");
            if (t.maxStars() <= t.stars()) return StarPlan.refuse("此裝備的星力已達到上限。");
            int target = t.stars() + 1;
            // "強化失敗時道具不會留下痕跡且會消失": a failure always destroys the equipment.
            return new StarPlan(null, amazingRate(e, target), 100, target, true);
        }
        return StarPlan.refuse("此卷軸目前尚未支援，道具未消耗。");
    }

    /** The 282 description table "N星：P%" (the last row, "13星以上", covers every higher star). */
    static int amazingRate(Entry e, int targetStar) {
        TreeMap<Integer, Integer> rates = new TreeMap<>();
        for (String part : e.attrs().getOrDefault("amazingRates", "").split(",")) {
            String[] kv = part.split(":");
            if (kv.length == 2) rates.put(Integer.parseInt(kv[0].trim()), Integer.parseInt(kv[1].trim()));
        }
        var floor = rates.floorEntry(targetStar);
        return floor == null ? 0 : floor.getValue();
    }

    // ---- bonus potential scrolls --------------------------------------------------------------------------------

    /** A bonus potential scroll decision: the hidden grade written to the bonus lines ({@code special}: all three). */
    public record BonusPlan(String refusal, ItemGrade hiddenGrade, boolean special) {
        public boolean refused() {
            return refusal != null;
        }
    }

    /** Grade rank 0 (none) .. 4 (legendary) of an option value, hidden or revealed. */
    public static int gradeRank(int optionValue) {
        ItemGrade g = ItemGrade.getGradeByOption(optionValue);
        return switch (g) {
            case HiddenRare, Rare, RareSecondary -> 1;
            case HiddenEpic, Epic -> 2;
            case HiddenUnique, Unique -> 3;
            case HiddenLegendary, Legendary -> 4;
            default -> 0;
        };
    }

    public static BonusPlan bonus(Entry e, int equipLevel, int baseOption0, int bonusOption0) {
        if (e == null || e.family() != Family.BONUS_POTENTIAL) return new BonusPlan("該物品不能用於此裝備。", null, false);
        if (e.has("reqEquipLevelMax") && equipLevel > e.i("reqEquipLevelMax", Integer.MAX_VALUE)) {
            return new BonusPlan("裝備等級不滿足物品要求。", null, false);
        }
        ItemGrade grade = switch (e.attrs().getOrDefault("grade", "RARE")) {
            case "EPIC" -> ItemGrade.HiddenEpic;
            case "UNIQUE" -> ItemGrade.HiddenUnique;
            case "LEGENDARY" -> ItemGrade.HiddenLegendary;
            default -> ItemGrade.HiddenRare;
        };
        boolean special = e.flag("special");
        if (special) {
            // "僅限已賦予潛在能力但並未賦予附加潛在能力的道具才可使用"
            if (baseOption0 == 0 || bonusOption0 != 0) {
                return new BonusPlan("只能用於已有潛在能力但沒有附加潛在能力的裝備。", null, false);
            }
        } else if (gradeRank(bonusOption0) >= grade.getVal()) {
            return new BonusPlan("此裝備的附加潛在能力等級已達到或超過此卷軸。", null, false);
        }
        return new BonusPlan(null, grade, special);
    }
}
