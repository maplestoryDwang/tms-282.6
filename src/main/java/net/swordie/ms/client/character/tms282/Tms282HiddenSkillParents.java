package net.swordie.ms.client.character.tms282;

import it.unimi.dsi.fastutil.ints.Int2ObjectMap;
import it.unimi.dsi.fastutil.ints.Int2ObjectOpenHashMap;
import net.swordie.ms.ServerConstants;
import net.swordie.ms.client.character.Char;
import net.swordie.ms.client.character.skills.info.SkillInfo;
import net.swordie.ms.connection.protocol.Protocol;
import net.swordie.ms.connection.protocol.ProtocolVersion;
import net.swordie.ms.constants.HexaBoostSkillConstants;
import net.swordie.ms.constants.JobConstants;
import net.swordie.ms.loaders.SkillData;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Arrays;
import java.util.List;

/**
 * TMS 282.3 hidden child skills: a skill the client uses (CP04B4 / attack) that is not in the character's skill
 * record because the 282 data only names it from a visible parent (same-name hidden form, {@code skillList},
 * {@code psdSkill}, {@code changeSkill}). The general rule: <b>the child is authorised when the character owns one of
 * its parents</b>, at the first owned parent's level (the list is ordered: same name, direct replacement, audit
 * guess, the rest), capped at the child's own maxLevel. A HEXA boost child uses the HEXA boost level of its base
 * skill when the server knows it.
 * <p>
 * Data: {@code data/protocol/tms282.3/hidden-skill-parents.tsv}, generated by
 * {@code research/tms2823/job-fixes-0929/gen_hidden_parents.py} from the audit
 * {@code skill-coverage-0929/hidden-children.tsv} (964 derivable parents) and the 282 Skill.wz. Only the same job
 * line (or V/HEXA common with common) is accepted unless the data names a replacement or the same name.
 * <p>
 * Every lookup returns 0 outside the 282.3 protocol.
 */
public final class Tms282HiddenSkillParents {
    public static final Path FILE = Path.of("data", "protocol", "tms282.3", "hidden-skill-parents.tsv");

    private static volatile Int2ObjectMap<int[]> parents;

    private Tms282HiddenSkillParents() {
    }

    private static boolean tms282() {
        return Protocol.active().version() == ProtocolVersion.TMS_282_3;
    }

    /** The parents of a hidden child, in preference order; empty when the child is not in the table. */
    public static int[] parentsOf(int childSkillId) {
        if (childSkillId == net.swordie.ms.client.jobs.flora.Tms282ArkFlight.SKILL)
            return new int[]{net.swordie.ms.client.jobs.flora.Tms282ArkFlight.PARENT};
        int[] p = table().get(childSkillId);
        return p == null ? new int[0] : p.clone();
    }

    public static boolean isHiddenChild(int skillId) {
        return skillId == net.swordie.ms.client.jobs.flora.Tms282ArkFlight.SKILL || table().containsKey(skillId);
    }

    /** Number of hidden children in the table (for checks). */
    public static int size() {
        return table().size();
    }

    /**
     * The level the character may use a hidden child at (0 = not authorised). The character's own record wins when
     * it has the child; otherwise the first owned parent decides. Native prerequisite forms that explicitly
     * share their parent's level keep that level even when an old child record exists. 0 outside 282.3.
     */
    public static int authorisedLevel(Char chr, int skillId) {
        if (chr == null || !tms282()) {
            return 0;
        }
        if (!meetsPrerequisites(chr, skillId)) {
            return 0;
        }
        if (skillId == net.swordie.ms.client.jobs.flora.Tms282ArkFlight.SKILL)
            return net.swordie.ms.client.jobs.flora.Tms282ArkFlight.learnedLevel(chr);
        // Current282007 is the finisher registered with006 (2B8C60/6825970), never an independently learned skill.
        if (skillId == 175141007) return Math.min(30, chr.getSkillLevel(175141006));
        int own = chr.getSkillLevel(skillId);
        if (own > 0 && skillId != 400041092 && skillId != 400040006) {
            return own;
        }
        int[] ps = table().get(skillId);
        if (ps == null) {
            // a hidden fixed-level skill of the character's own book has no visible parent and is never learned with
            // SP (e.g. 152101000 古代水晶, invisible + fixLevel 1 in book 15210): the book stage authorises it
            SkillInfo fixed = SkillData.getSkillInfoById(skillId);
            return fixed != null && fixed.isInvisible() && fixed.getFixLevel() > 0 && fixed.getRootId() < 20000
                    && Tms282SkillLearning.bookStage(fixed.getRootId()) > 0
                    && Tms282SkillLearning.belongs(chr, fixed.getRootId())
                    && Tms282SkillLearning.requirementsMet(chr, fixed) ? fixed.getFixLevel() : 0;
        }
        int level = 0;
        if (HexaBoostSkillConstants.isHexaBoostSkill(skillId)) {
            int base = HexaBoostSkillConstants.getBaseSkillId(skillId);
            if (base != skillId && chr.getSkillLevel(base) > 0) {
                level = HexaBoostSkillConstants.getHexaBoostLevel(chr, base);
            }
        }
        if (level <= 0) {
            for (int parent : ps) {
                // one level of indirection: a parent that is itself a hidden child of an owned skill
                int pl = chr.getSkillLevel(parent);
                if (pl <= 0 && table().containsKey(parent)) {
                    for (int grand : table().get(parent)) {
                        if (grand != skillId && (pl = chr.getSkillLevel(grand)) > 0) {
                            break;
                        }
                    }
                }
                if (pl > 0) {
                    level = pl;
                    break;
                }
            }
        }
        if (level <= 0) {
            return 0;
        }
        SkillInfo si = SkillData.getSkillInfoById(skillId);
        if (si != null && si.getMaxLevel() > 0) {
            level = Math.min(level, si.getMaxLevel());
        }
        return level;
    }

    /**
     * The level CP04B4 / attack checks should use: the owned level, else the hidden-child level on 282.3.
     * (Drop-in for {@code chr.getSkillLevel(skillId)} at a "does the character have the skill" gate.)
     */
    public static int useLevel(Char chr, int skillId) {
        if (tms282() && skillId == net.swordie.ms.client.jobs.flora.Tms282ArkFlight.SKILL)
            return net.swordie.ms.client.jobs.flora.Tms282ArkFlight.learnedLevel(chr);
        if (chr != null && tms282() && (!meetsPrerequisites(chr, skillId)
                || !Tms282SkillLearning.fixedUseAllowed(chr, skillId))) {
            return 0;
        }
        if (tms282() && (skillId == 400041092 || skillId == 175141007 || skillId == 400040006)) return authorisedLevel(chr, skillId);
        int own = chr == null ? 0 : chr.getSkillLevel(skillId);
        return own > 0 ? own : authorisedLevel(chr, skillId);
    }

    /** The parent table is an OR-list; these native forms additionally require their own job and source skill.
     * Keep the checks even for an old saved child row, which must not bypass its prerequisite. */
    private static boolean meetsPrerequisites(Char chr, int skillId) {
        return switch (skillId) {
            case 175141006, 175141007 -> JobConstants.isMoXuan(chr.getJob())
                    && chr.getSkillLevel(175121003) >= 30 && chr.getSkillLevel(175141006) > 0;
            // Native 1095A62..1095B5B maps Blade Tempest's opening to the learned held skill.
            case 400040006 -> JobConstants.isDualBlade(chr.getJob()) && chr.getSkillLevel(400041006) > 0;
            // 282 Skill.wz 4301010/req explicitly requires maxed 4001011; native 11A2194 selects job 430..439.
            case 4301010 -> JobConstants.isDualBlade(chr.getJob()) && chr.getSkillLevel(4001011) >= 5;
            // Native 1098151..109816A normalises 61001006 to 61001002.
            case 61001006 -> JobConstants.isKaiser(chr.getJob()) && chr.getSkillLevel(61001002) > 0;
            // Native 1189F00 maps 400001046 to 400001048 only for Flora (15000..15999).
            case 400001048 -> JobConstants.isFlora(chr.getJob()) && chr.getSkillLevel(400001046) > 0;
            // Native 129CBDD..129CC02: installed Omega Blaster uses its keydown parent's learned level.
            case 400041092 -> JobConstants.isXenon(chr.getJob()) && chr.getSkillLevel(400041007) > 0;
            // The same native dispatcher selects the Nova/Anima forms, not same-name guesses.
            case 400001047 -> JobConstants.isNova(chr.getJob()) && chr.getSkillLevel(400001046) > 0;
            case 400001049 -> (JobConstants.isHoYoung(chr.getJob()) || JobConstants.isLara(chr.getJob())
                    || JobConstants.isRen(chr.getJob())) && chr.getSkillLevel(400001046) > 0;
            default -> true;
        };
    }

    static Int2ObjectMap<int[]> table() {
        Int2ObjectMap<int[]> t = parents;
        if (t == null) {
            synchronized (Tms282HiddenSkillParents.class) {
                t = parents;
                if (t == null) {
                    t = load(Path.of(ServerConstants.DIR).resolve(FILE));
                    parents = t;
                }
            }
        }
        return t;
    }

    /** Parses the table (header and {@code #} lines skipped); a missing file gives an empty table. */
    public static Int2ObjectMap<int[]> load(Path path) {
        Int2ObjectMap<int[]> out = new Int2ObjectOpenHashMap<>();
        List<String> lines;
        try {
            lines = Files.readAllLines(path, StandardCharsets.UTF_8);
        } catch (IOException e) {
            System.out.println("[TMS282] hidden-skill-parents: " + path + " not readable (" + e + "); no hidden children");
            return out;
        }
        for (String line : lines) {
            if (line.isBlank() || line.startsWith("#") || line.startsWith("child\t")) {
                continue;
            }
            String[] f = line.split("\t", -1);
            if (f.length < 2 || f[1].isBlank()) {
                continue;
            }
            try {
                int child = Integer.parseInt(f[0].trim());
                int[] ps = Arrays.stream(f[1].split(",")).map(String::trim).filter(s -> !s.isEmpty())
                        .mapToInt(Integer::parseInt).filter(p -> p != child).toArray();
                if (ps.length > 0) {
                    out.put(child, ps);
                }
            } catch (NumberFormatException ignored) {
                // malformed row: skipped
            }
        }
        return out;
    }

    /** For checks: replace the loaded table. */
    static void reset(Int2ObjectMap<int[]> table) {
        parents = table;
    }
}
